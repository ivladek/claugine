def _imfile(path, tag, facility="daemon", extra=""):
    return (
        "input (\n"
        '  type = "imfile"\n'
        f'  file = "{path}"\n'
        f'  tag = "{tag}"\n'
        '  severity = "info"\n'
        f'  facility = "{facility}"\n' + (extra or '  readMode = "0"\n') + '  freshStartTail = "on"\n'
        '  reopenOnTruncate = "on"\n'
        ")\n"
    )


def _by_tag(prefix, log_type):
    return (
        f'\nif ( $syslogtag startswith "{prefix}" ) then {{\n'
        f'  set $.log_type = "{log_type}";\n'
        "  call send_logs\n"
        "  stop\n"
        "}\n"
    )


